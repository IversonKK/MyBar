def get_story(row):
    name = str(row['酒名 (必須與圖片同名)']).strip()
    if name in stories_map:
        return stories_map[name]
    
    # 防呆：如果有名稱些微不符的，依據標籤給予優雅的引言
    tags = str(row['標籤 (用逗號隔開)'])
    base = "經典"
    if '琴酒' in tags: base = "琴酒草本"
    elif '伏特加' in tags: base = "伏特加俐落"
    elif '蘭姆酒' in tags: base = "蘭姆酒熱帶"
    elif '威士忌' in tags: base = "威士忌醇厚"
    elif '白蘭地' in tags: base = "白蘭地果香"
    elif '龍舌蘭' in tags: base = "龍舌蘭大地"
    return f"一款極具層次與魅力的{base}系經典風味調酒。透過完美的比例與傳統技法，展現出獨特的風味平衡與酒吧歷史文化傳承。"

df['故事與敘述'] = df.apply(get_story, axis=1)

